package com.example.SpringBootSpringDataExample.StudentVsCourseManyToMany.entity;

import com.fasterxml.jackson.annotation.JsonManagedReference;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.util.Set;

@Entity     // PARENT
@Table(name= "STUDENT_TBL")
@Setter
@Getter
@AllArgsConstructor
@NoArgsConstructor
public class Student {

    @Id
    @GeneratedValue(strategy = GenerationType.AUTO)     //this will autogenerate <id>
    private Long id;
    private String name;
    private int age;
    private String dept;

    @ManyToMany(fetch= FetchType.LAZY, cascade= CascadeType.ALL)    /*fetch: defines when the action arises
                                          FetchType.EAGER describes that data should be initialized on the spot.
                                          FetchType.LAZY describes that data should be initialized as late as possible.
                                                                     *cascade: defines Series connection or chaining*/
    @JoinTable(name= "STUDENT_COURSE_TBL",              /*tells JPA/Hibernate to create one additional/autogenerated
                                                          reference-table for the many-to-many-relation*/
        joinColumns= {
            @JoinColumn(name= "student_id", referencedColumnName= "id")     //to map Student.id : STUDENT_COURSE_TBL.student_id
        },
        inverseJoinColumns= {
            @JoinColumn(name= "course_id", referencedColumnName= "id")
        })
    @JsonManagedReference   //to bind CHILD
    private Set<Course> courses;        //CHILD refers to in its @ManyToMany
}
